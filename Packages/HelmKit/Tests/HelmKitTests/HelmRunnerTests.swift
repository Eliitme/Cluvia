import Foundation
import KubeKit
import Testing
@testable import HelmKit

struct HelmDecodingTests {
    @Test func releasesAndHistoryDecodeLeniently() throws {
        let list = #"[{"name":"demo","namespace":"apps","revision":"3","updated":"2026-10-20 15:22:34 +0700","status":"deployed","chart":"demo-0.1.0","app_version":"1.16.0"}]"#
        let release = try #require(try HelmDecoding.releases(Data(list.utf8)).first)
        #expect(release.revision == 3 && release.chartName == "demo" && release.id == "apps/demo")
        let history = #"[{"revision":1,"status":"superseded","chart":"demo-0.1.0"},{"revision":2,"status":"deployed","chart":"demo-0.1.0","description":"Upgrade complete"}]"#
        #expect(try HelmDecoding.history(Data(history.utf8)).map(\.revision) == [2, 1])
        #expect(HelmRelease(name: "x", namespace: "n", revision: 1, updated: "", status: "", chart: "my-chart-v2", appVersion: "").chartName == "my-chart-v2")
        #expect(HelmRunner.parseMajorVersion("v4.0.1+g12500dd\n") == 4)
        #expect(HelmRunner.parseMajorVersion("v3.15.2+gabc") == 3)
        #expect(HelmRunner.parseMajorVersion("garbage") == nil)
    }
}

/// Full lifecycle against a real cluster with a chart generated by `helm create` (no network needed).
/// Opt-in: `CLUVIA_IT_CONTEXT=<context>`; skipped when helm is not installed.
@Suite(.enabled(if: ProcessInfo.processInfo.environment["CLUVIA_IT_CONTEXT"] != nil), .serialized)
struct HelmLifecycleIntegrationTests {
    @Test func installUpgradeRollbackUninstall() async throws {
        let context = try #require(ProcessInfo.processInfo.environment["CLUVIA_IT_CONTEXT"])
        guard let helm = await HelmRunner.locate(context: context) else { return }
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: dir) }
        _ = try await ProcessRunner.run(helm.executable, arguments: ["create", dir.appendingPathComponent("chart").path])
        let chart = dir.appendingPathComponent("chart").path
        let release = "cluvia-it-helm", namespace = "cluvia-it-helm"
        let base = "image: {repository: busybox, tag: \"1.36\"}\nlivenessProbe: null\nreadinessProbe: null\n"
        try? await helm.uninstall(release: release, namespace: namespace)

        try await helm.upgradeOrInstall(release: release, namespace: namespace, chart: chart, version: nil,
                                        values: base + "replicaCount: 1\n", install: true)
        try await helm.upgradeOrInstall(release: release, namespace: namespace, chart: chart, version: nil,
                                        values: base + "replicaCount: 2\n", install: false)
        #expect(try await helm.values(release: release, namespace: namespace).contains("replicaCount: 2"))
        #expect(try await helm.releases().contains { $0.name == release && $0.revision == 2 })

        try await helm.rollback(release: release, namespace: namespace, revision: 1)
        let history = try await helm.history(release: release, namespace: namespace)
        #expect(history.first?.revision == 3)
        #expect(try await helm.values(release: release, namespace: namespace).contains("replicaCount: 1"))
        #expect(try await helm.manifest(release: release, namespace: namespace).contains("kind: Deployment"))

        try await helm.uninstall(release: release, namespace: namespace)
        #expect(try await !helm.releases().contains { $0.name == release })
        await #expect(throws: HelmError.self) { try await helm.history(release: release, namespace: namespace) }
    }
}
